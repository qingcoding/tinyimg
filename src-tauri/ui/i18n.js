// 主语言 → 受支持 locale（中文按文字变体 / 地区细分，见 SCRIPT_REGION_MAP）
const PRIMARY_MAP = {
  zh: 'zh-CN',
  en: 'en',
  ja: 'ja',
  ko: 'ko',
  fr: 'fr',
  de: 'de',
  es: 'es',
  ru: 'ru',
  pt: 'pt',
};

// 中文细分：文字（Hans/Hant）优先于地区（CN/SG/TW/HK/MO）
const ZH_VARIANT_MAP = {
  hans: 'zh-CN',
  hant: 'zh-TW',
  cn: 'zh-CN',
  sg: 'zh-CN',
  tw: 'zh-TW',
  hk: 'zh-TW',
  mo: 'zh-TW',
};

/**
 * 把 BCP-47 标签归一到受支持 code。
 * - zh-Hans / zh / zh-CN / zh-SG → zh-CN；zh-Hant / zh-TW / zh-HK / zh-MO → zh-TW
 * - en-* → en；其余取主语言匹配
 * - 大小写不敏感；无法匹配返回 null
 * @param {string} tag BCP-47 语言标签（如 'zh-Hant-TW'）
 * @returns {string|null}
 */
export function normalizeLocale(tag) {
  if (typeof tag !== 'string') return null;
  const parts = tag.trim().toLowerCase().split(/[-_]/).filter(Boolean);
  if (parts.length === 0) return null;
  const [primary, ...rest] = parts;
  const base = PRIMARY_MAP[primary];
  if (!base) return null;
  if (primary === 'zh') {
    for (const p of rest) {
      if (ZH_VARIANT_MAP[p]) return ZH_VARIANT_MAP[p];
    }
    return 'zh-CN';
  }
  return base;
}

/**
 * 从系统语言列表探测界面语言。
 * @param {string[]|string} systemLangs navigator.languages 数组（或单个字符串）
 * @returns {string} 首个可归一化 code；全部失败回落 FALLBACK_LOCALE
 */
export function detectLocale(systemLangs) {
  const tags = typeof systemLangs === 'string' ? [systemLangs] : systemLangs;
  if (Array.isArray(tags)) {
    for (const tag of tags) {
      const code = normalizeLocale(tag);
      if (code) return code;
    }
  }
  return FALLBACK_LOCALE;
}

