/**
 * 构造翻译器。
 * @param {string} locale 目标语言 code（不在 DICTS 中时整体回落中文）
 * @param {Record<string, Record<string, string>>} [dicts] 字典集（默认 DICTS，供测试注入）
 * @returns {{ locale: string, t: (key: string, vars?: Record<string, unknown>) => string }}
 */
export function createTranslator(locale, dicts = DICTS) {
  const fallbackDict = (dicts && dicts[FALLBACK_LOCALE]) || {};
  const dict = (dicts && dicts[locale]) || fallbackDict;
  return {
    locale,
    t(key, vars) {
      let text = Object.prototype.hasOwnProperty.call(dict, key) ? dict[key] : fallbackDict[key];
      if (text === undefined) text = key;
      if (vars) {
        text = text.replace(/\{(\w+)\}/g, (match, name) =>
          Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
        );
      }
      return text;
    },
  };
}
